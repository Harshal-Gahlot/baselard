import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const API_KEY = process.env.YOUTUBE_API_KEY;
const CHANNEL = process.env.YOUTUBE_CHANNEL;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

if (!API_KEY || !CHANNEL) {
  console.error('Missing YOUTUBE_API_KEY or YOUTUBE_CHANNEL in .env. See README.md.');
  process.exit(1);
}

async function youtube(path, params) {
  const url = new URL(`https://www.googleapis.com/youtube/v3/${path}`);
  for (const [key, value] of Object.entries({ ...params, key: API_KEY })) url.searchParams.set(key, value);
  const response = await fetch(url);
  const payload = await response.json();
  if (!response.ok) throw new Error(payload?.error?.message ?? `YouTube API request failed (${response.status})`);
  return payload;
}

try {
  const channelLookup = CHANNEL.startsWith('UC')
    ? { id: CHANNEL }
    : { forHandle: CHANNEL.startsWith('@') ? CHANNEL : `@${CHANNEL}` };
  const channel = await youtube('channels', { part: 'contentDetails', ...channelLookup });
  const uploadsId = channel.items?.[0]?.contentDetails?.relatedPlaylists?.uploads;
  if (!uploadsId) throw new Error('No uploads playlist found. Check YOUTUBE_CHANNEL.');

  const releases = [];
  let pageToken = '';
  // Keep the homepage/archive light: sync at most the latest 50 public uploads.
  for (let page = 0; page < 2; page += 1) {
    const params = { part: 'snippet,contentDetails', playlistId: uploadsId, maxResults: '25' };
    if (pageToken) params.pageToken = pageToken;
    const result = await youtube('playlistItems', params);
    for (const item of result.items ?? []) {
      const videoId = item.contentDetails?.videoId;
      const snippet = item.snippet ?? {};
      if (!videoId || snippet.title === 'Private video' || snippet.title === 'Deleted video') continue;
      releases.push({
        videoId,
        title: snippet.title ?? 'Untitled upload',
        description: snippet.description ?? '',
        publishedAt: snippet.publishedAt ?? '',
        thumbnail: snippet.thumbnails?.maxres?.url ?? snippet.thumbnails?.high?.url ?? snippet.thumbnails?.medium?.url ?? '',
      });
    }
    pageToken = result.nextPageToken ?? '';
    if (!pageToken) break;
  }

  const target = resolve(ROOT, 'src/data/generated/youtube-releases.ts');
  const source = `/** Generated by scripts/sync-youtube.mjs. Review before publishing. */\nexport const YOUTUBE_RELEASES = ${JSON.stringify(releases, null, 2)} as const;\n`;
  await writeFile(target, source, 'utf8');
  console.log(`Synced ${releases.length} public uploads to src/data/generated/youtube-releases.ts`);
  console.log('Review the new uploads and verify studio credits before treating them as Baselard projects.');
} catch (error) {
  console.error(`YouTube sync failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
